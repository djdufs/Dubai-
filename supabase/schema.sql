-- Dubai trip guide — schema, grants, RLS
-- Applied to Supabase project (ref in README). No secrets here.

create extension if not exists pgcrypto;

-- ---------- places (숙소 / 출장지 / 맛집 / 관광) ----------
create table if not exists public.dubai_places (
  id          bigint generated by default as identity primary key,
  category    text not null default '관광',
  name        text not null,
  address     text,
  lat         double precision,
  lng         double precision,
  start_at    text,
  end_at      text,
  memo        text,
  booking_ref text,
  author      text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ---------- notes / couple chat ----------
create table if not exists public.dubai_notes (
  id         bigint generated by default as identity primary key,
  author     text not null default '익명',
  body       text,
  image_url  text,
  created_at timestamptz not null default now()
);

-- ---------- checklist ----------
create table if not exists public.dubai_checklist (
  id         bigint generated by default as identity primary key,
  label      text not null,
  done       boolean not null default false,
  author     text,
  created_at timestamptz not null default now()
);

-- ---------- shopping / gift wishlist ----------
create table if not exists public.dubai_shopping (
  id          bigint generated by default as identity primary key,
  name        text not null,
  category    text not null default '기념품·기타',
  price_aed   numeric(10,2),
  qty         integer not null default 1,
  memo        text,
  requester   text,
  photo_url   text,
  done        boolean not null default false,
  sort        integer not null default 0,
  author      text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists dubai_places_created_idx on public.dubai_places (created_at);
create index if not exists dubai_notes_created_idx  on public.dubai_notes (created_at);
create index if not exists dubai_checklist_id_idx   on public.dubai_checklist (id);
create index if not exists dubai_shopping_created_idx on public.dubai_shopping (created_at);

-- ---------- privileges ----------
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.dubai_places    to anon, authenticated;
grant select, insert, update, delete on public.dubai_notes     to anon, authenticated;
grant select, insert, update, delete on public.dubai_checklist to anon, authenticated;
grant select, insert, update, delete on public.dubai_shopping  to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- ---------- RLS: two-person shared space, key holders only ----------
alter table public.dubai_places    enable row level security;
alter table public.dubai_notes     enable row level security;
alter table public.dubai_checklist enable row level security;
alter table public.dubai_shopping  enable row level security;

drop policy if exists dubai_places_all on public.dubai_places;
create policy dubai_places_all on public.dubai_places
  for all to anon, authenticated using (true) with check (true);

drop policy if exists dubai_notes_all on public.dubai_notes;
create policy dubai_notes_all on public.dubai_notes
  for all to anon, authenticated using (true) with check (true);

drop policy if exists dubai_checklist_all on public.dubai_checklist;
create policy dubai_checklist_all on public.dubai_checklist
  for all to anon, authenticated using (true) with check (true);

drop policy if exists dubai_shopping_all on public.dubai_shopping;
create policy dubai_shopping_all on public.dubai_shopping
  for all to anon, authenticated using (true) with check (true);

-- ---------- storage: dubai-photos (public bucket) ----------
drop policy if exists dubai_photos_read   on storage.objects;
create policy dubai_photos_read on storage.objects
  for select to anon, authenticated using (bucket_id = 'dubai-photos');

drop policy if exists dubai_photos_insert on storage.objects;
create policy dubai_photos_insert on storage.objects
  for insert to anon, authenticated with check (bucket_id = 'dubai-photos');

drop policy if exists dubai_photos_update on storage.objects;
create policy dubai_photos_update on storage.objects
  for update to anon, authenticated using (bucket_id = 'dubai-photos') with check (bucket_id = 'dubai-photos');

drop policy if exists dubai_photos_delete on storage.objects;
create policy dubai_photos_delete on storage.objects
  for delete to anon, authenticated using (bucket_id = 'dubai-photos');
